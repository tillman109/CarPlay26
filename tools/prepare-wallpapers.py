#!/usr/bin/env python3
"""Download and validate high-res iOS 26 CarPlay stock artwork, then prepare 2048px/512px assets.
No approximated/generated patterned wallpapers; missing or invalid stock artwork aborts CI.
"""
import json, hashlib, io, urllib.request, sys
from pathlib import Path
from PIL import Image, ImageOps

ROOT=Path(__file__).resolve().parent.parent
SOURCES=json.loads((ROOT/'WallpaperSources.json').read_text())
DEST=ROOT/'layout/usr/lib/TweakInject/CarPlay26Wallpapers'
DEST.mkdir(parents=True,exist_ok=True)

# These match the three stock solid colors reported for iOS 26 CarPlay.
# Pixel shades cannot be firmware-verified from the archive and are intentionally
# not presented as extracted Apple image files.
SOLIDS={
 'solid-white': {'light':(246,247,249),'dark':(22,24,27)},
 'solid-blue':  {'light':(188,223,245),'dark':(22,49,72)},
 'solid-beige': {'light':(225,210,187),'dark':(59,49,39)},
}

def target_image(image,size):
    # iOS16 APIs expect square artwork, but the real iOS26 source is landscape.
    # Crop centrally (never stretch), then downsample with Lanczos for high quality.
    return ImageOps.fit(image,(size,size),method=Image.Resampling.LANCZOS,centering=(.5,.5))

# The folder is generated by this tool; drop only previous image outputs so
# repeated builds cannot package both the old large PNGs and new JPEGs.
ALL_PAIRS=[f'{name}-{style}' for name in list(SOURCES)+list(SOLIDS)
           for style in ('light','dark')]
for pair in ALL_PAIRS:
    for kind in ('full','thumb'):
        for ext in ('.png','.jpg'):
            (DEST/f'{pair}-{kind}{ext}').unlink(missing_ok=True)

def save(pair,image,patterned):
    for kind,side in (('full',2048),('thumb',512)):
        resized=target_image(image,side).convert('RGB')
        # Quality 92 + 4:4:4 keeps full chroma resolution and avoids visible
        # colour smearing on the smooth wallpaper gradients. No up/downscaling
        # relative to the previous PNG output.
        extension='jpg' if patterned else 'png'
        out=DEST/f'{pair}-{kind}.{extension}'
        if patterned:
            resized.save(out,format='JPEG',quality=92,subsampling=0,optimize=True)
        else:
            resized.save(out,format='PNG',optimize=True)
        with Image.open(out) as check:
            check.verify()
        with Image.open(out) as check:
            if check.size!=(side,side): raise RuntimeError(f'Invalid output: {out}')
            if check.format != ('JPEG' if patterned else 'PNG'):
                raise RuntimeError(f'Invalid image format: {out}')
        print(f'{out.relative_to(ROOT)} {out.stat().st_size} bytes',flush=True)

for name,variants in SOURCES.items():
    if set(variants)!={'light','dark'}: raise ValueError(f'Incomplete variants for {name}')
    for style,url in variants.items():
        if not url.startswith('https://wallpapers.betaprofiles.com/'): raise ValueError(url)
        print(f'Downloading {name} {style}: {url}',flush=True)
        req=urllib.request.Request(url,headers={
          'User-Agent':'Mozilla/5.0 (compatible; CarPlay26Build/1.0)',
          'Referer':'https://betaprofiles.com/',
          'Accept':'image/png,image/*;q=0.8',
        })
        with urllib.request.urlopen(req,timeout=90) as response:
            data=response.read(20_000_001)
        if not 200_000 < len(data) < 20_000_000: raise ValueError(f'Unexpected image byte count {name}/{style} {len(data)}')
        if not data.startswith(b'\x89PNG\r\n\x1a\n'): raise ValueError(f'Not PNG: {name}/{style}')
        image=Image.open(io.BytesIO(data))
        image.load()
        if image.size != (4000,2182):
            raise ValueError(f'Not 4000x2182 source: {name}/{style} {image.size}')
        print(f'Source SHA256 {name}/{style}: {hashlib.sha256(data).hexdigest()}',flush=True)
        save(f'{name}-{style}',image.convert('RGB'),patterned=True)

for name,styles in SOLIDS.items():
    for style,rgb in styles.items():
        image=Image.new('RGB',(2048,2048),rgb)
        save(f'{name}-{style}',image,patterned=False)
expected={f'{pair}-{kind}.{("jpg" if not pair.startswith("solid-") else "png")}'
          for pair in ALL_PAIRS for kind in ('full','thumb')}
actual={p.name for p in DEST.iterdir() if p.is_file() and p.suffix.lower() in ('.png','.jpg')}
if actual != expected:
    raise RuntimeError(f'Asset mismatch: missing={sorted(expected-actual)}, unexpected={sorted(actual-expected)}')
patterned_bytes=sum((DEST/n).stat().st_size for n in expected if n.endswith('.jpg'))
solid_bytes=sum((DEST/n).stat().st_size for n in expected if n.endswith('.png'))
print(f'Success: {len(actual)} assets (24 JPEG + 12 PNG), {patterned_bytes+solid_bytes:,} bytes total',flush=True)
